/** Contents of public/legal.css. */
export function buildLegalCss(): string {
  return `/* Generated by scripts/build-legal-css.ts from lib/design-css.ts. Do not edit by hand. */\n${designCss}\n${LEGAL_CSS}`;
}

const stageDeclarations = Object.entries(stageVars)
  .map(([name, value]) => `${name}:${value};`)
  .join('');

/** Stage tokens and fonts only: the export is a dark, printable snapshot with no Daylight block. */
const exportTokens = `:root{color-scheme:dark;${stageDeclarations}}
${fontFaceCss}`;

/** The offline page needs both schemes, the fonts, the base rules and the CTA pill, inline. */
const offlineTokens = designCss;

type Block = 'design-css' | 'design-mark';

const begin = (name: Block) => (name === 'design-css' ? `/* ${name}:begin */` : `<!-- ${name}:begin -->`);
const end = (name: Block) => (name === 'design-css' ? `/* ${name}:end */` : `<!-- ${name}:end -->`);

/** Replaces the text between a block's markers. Throws when the markers are missing. */
export function replaceBlock(html: string, name: Block, content: string): string {
  const from = html.indexOf(begin(name));
  const to = html.indexOf(end(name));
  if (from === -1 || to === -1 || to < from) throw new Error(`Missing ${name} markers`);
  return `${html.slice(0, from + begin(name).length)}\n${content}\n${html.slice(to)}`;
}

/** Expected full text of every generated file, keyed by file name under public/. */
export function buildAll(read: (file: string) => string): Record<string, string> {
  return {
    'legal.css': buildLegalCss(),
    'offline.html': replaceBlock(replaceBlock(read('offline.html'), 'design-css', offlineTokens), 'design-mark', festieMarkSvg()),
    'export-template.html': replaceBlock(read('export-template.html'), 'design-css', exportTokens),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const read = (file: string) => fs.readFileSync(path.join(PUBLIC_DIR, file), 'utf8');
  const stale: string[] = [];
  for (const [file, text] of Object.entries(buildAll(read))) {
    const target = path.join(PUBLIC_DIR, file);
    const current = fs.existsSync(target) ? read(file) : '';
    if (current === text) continue;
    if (check) stale.push(file);
    else fs.writeFileSync(target, text);
  }
  if (stale.length) {
    console.error(`Stale generated files: ${stale.join(', ')}. Run: node --import tsx/esm scripts/build-legal-css.ts`);
    process.exit(1);
  }
}
