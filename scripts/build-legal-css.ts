/**
 * Writes the generated parts of the static pages from lib/design-css.ts, so a token change
 * reaches them with one command:
 *
 *   node --import tsx/esm scripts/build-legal-css.ts           write the files
 *   node --import tsx/esm scripts/build-legal-css.ts --check   fail when a committed file is stale
 *
 * Generated: public/legal.css (the five legal pages), the token block and the inline mark in
 * public/offline.html, and the token block in public/export-template.html. The two HTML files
 * must stay self-contained (the offline page is shown with no network, the export is saved and
 * sent), so their generated parts sit between marker comments instead of in a linked file.
 */

